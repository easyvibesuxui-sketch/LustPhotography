// `tier` gates the full media; `blur` is a public, heavily blurred teaser.
// Videos also carry a poster frame with its own (often tamer) tier.
export type Art = {
  scene: Scene;
  tone: Tone;
  src?: string;
  video?: string;
  poster?: string;
  level?: Level;
  tier?: Tier;
  blur?: string;
  posterTier?: Tier;
  posterBlur?: string;
  /** Width ÷ height of the original file, so frames can match it. */
  aspect?: number;
  /** Media id, e.g. "c03" or "n12". */
  id?: string;
};

export type Chapter = { t: string; label: string };

